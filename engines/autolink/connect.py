#!/usr/bin/env python3
"""
connect.py — Typed Connections enricher for Open Brain
========================================================
Problem: wikilinks in PNs usually carry their context AFTER the link
  (e.g. "[[PN-A]] — this note explains...")
but autolink reads the ~80 chars BEFORE the link to assign the type.
Result: everything ends up as `menciona` (mentions).

Solution: append a "## Typed Connections" section at the end of each PN
with sentences that put the verb BEFORE the link:
  "Feeds [[PN-A]] by explaining the underlying mechanism."
  "Contradicts [[PN-B]] in that the activation condition is different."

Autolink detects them and produces high-signal edges.

WORKFLOW
--------
  status  → how many PNs have / need Typed Connections
  scan    → export PN→PN pairs for the LLM to classify (JSON)
  apply   → write the connections generated by the LLM
  preview → show the pairs of one specific PN (dry-run)

USAGE
-----
  python3 connect.py status
  python3 connect.py scan [--limit N] [--json]
  python3 connect.py apply --json '<payload>'
  python3 connect.py preview "<partial-title>"

apply PAYLOAD (array of notes; note_path is relative to the vault root):
  [
    {
      "note_path": "Permanent Notes/...",
      "connections": [
        {
          "type": "alimenta",
          "target_title": "Exact title of the target PN",
          "sentence": "Feeds [[Exact title of the target PN]] because..."
        }
      ]
    }
  ]

PROMPT FOR THE LLM:
  For each batch from scan, classify the relation between source and each target.
  Use ONLY these types (in priority order, strongest first):
    refuta, contradice, refina, extiende, depende_de, ejemplifica,
    validado_por, aplica_a, alimenta, operacionaliza, sintetiza_desde, cross_domain
  (refutes, contradicts, refines, extends, depends on, exemplifies,
   validated by, applies to, feeds, operationalizes, synthesized from, cross-domain)
  If the relation is no more specific than menciona/relacionada_con → use "skip".
  Write a one-line sentence in the language of the source note, starting with the
  verb for the type (e.g. "Feeds" / "Alimenta" for alimenta).
  Format: "{Capitalized verb} [[{exact title}]] {short justification (≤12 words)}."
  Reply as a JSON array with the same structure as the input, adding
  "type" (the identifier above) and "sentence" to each target (or "type": "skip").
"""

import os
import sys
import json
import re
import argparse
from pathlib import Path
from datetime import date

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------
SCRIPT_DIR   = Path(__file__).resolve().parent          # autolink/
# Vault root: $OPEN_BRAIN_VAULT if set, otherwise the parent of this autolink/ folder.
VAULT_INNER  = Path(os.environ.get("OPEN_BRAIN_VAULT") or SCRIPT_DIR.parent)
PN_DIR       = VAULT_INNER / "Permanent Notes"

SECTION_HEADER = "## Typed Connections"

# Prefixes indicating the link does NOT point to a PN
NON_PN_PREFIXES = (
    "Dossiers/", "Search Terms/", "Search Terms /", "Cases/",
    "Literature Notes/", "Fleeting Notes/", "Inbox/",
    "Resources/", "Playbooks/", "Mentors/", "Authors/",
    "Skills/", "Projects/", "Manuscripts/", "Templates/",
    "Applications/", "Domain Index",
)

# Verbs autolink classifies as signal types (Spanish identifiers + English equivalents)
TYPED_VERBS = [
    "refuta", "contradice", "refina", "extiende", "depende_de", "depende de",
    "ejemplifica", "validado_por", "validado por", "aplica_a", "aplica a",
    "alimenta", "operacionaliza", "sintetiza_desde", "sintetiza desde",
    "sintetizada_en", "sintetizada en", "cross_domain", "cross domain",
    "refuerza", "se_ancla_en", "se ancla en",
    # English equivalents (matched by autolink/patterns.py as well)
    "refutes", "contradicts", "refines", "extends", "depends on",
    "exemplifies", "illustrates", "validated by", "applies to", "feeds",
    "operationalizes", "synthesized from", "synthesized into", "reinforces",
    "anchored in",
]

SKIP_TYPES   = {"relacionada_con", "menciona", "skip", "none", ""}
VALID_TYPES  = {
    "refuta", "contradice", "refina", "extiende", "depende_de",
    "ejemplifica", "validado_por", "aplica_a", "alimenta",
    "operacionaliza", "sintetiza_desde", "sintetizada_en", "cross_domain",
    "refuerza", "se_ancla_en",
}
TODAY = date.today().isoformat()


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def is_pn_link(link_title: str) -> bool:
    """True if the link looks like it points to a PN (not a dossier, LN, etc.)."""
    for prefix in NON_PN_PREFIXES:
        if link_title.startswith(prefix):
            return False
    # Links with / usually point to subdirs that aren't PNs
    if "/" in link_title:
        return False
    return True


def already_typed(context_before: str) -> bool:
    """True if the ~80 chars before the link already contain a typed verb."""
    ctx = context_before.lower()
    return any(v in ctx for v in TYPED_VERBS)


def get_body(fpath: Path) -> str:
    """Extract a note's body (without frontmatter)."""
    txt = fpath.read_text(encoding="utf-8", errors="ignore")
    parts = txt.split("---")
    if len(parts) >= 3:
        return "---".join(parts[2:]).strip()
    return txt


def extract_untyped_pn_links(fpath: Path) -> list[dict]:
    """
    Extract wikilinks from a PN's body that:
    - Point to PNs (not dossiers, etc.)
    - Have no typed verb in the 80 chars before them
    Returns: [{title, context_before, context_after}]
    """
    body = get_body(fpath)
    # Exclude the Typed Connections section itself
    body_for_scan = body.split(SECTION_HEADER)[0]

    links = []
    seen = set()
    for m in re.finditer(r'\[\[([^\]]+)\]\]', body_for_scan):
        link_title = m.group(1).strip()
        # Deduplicate
        if link_title in seen:
            continue
        if not is_pn_link(link_title):
            continue
        seen.add(link_title)
        # Context before (up to 80 chars)
        start = max(0, m.start() - 80)
        ctx_before = body_for_scan[start:m.start()]
        # Skip if already typed
        if already_typed(ctx_before):
            continue
        # Context after (up to 120 chars for human readability in scan output)
        ctx_after = body_for_scan[m.end():m.end() + 120].split("\n")[0].strip()
        links.append({
            "title": link_title,
            "context_before": ctx_before.strip()[-60:],
            "context_after": ctx_after[:100],
        })
    return links


def get_body_excerpt(target_title: str) -> str:
    """Try to get a PN's body excerpt by title."""
    # Exact filename match first
    candidate = PN_DIR / f"{target_title}.md"
    if candidate.exists():
        return get_body(candidate)[:400]
    # Partial match
    target_lower = target_title.lower()
    for f in PN_DIR.rglob("*.md"):
        if target_lower in f.stem.lower() or f.stem.lower() in target_lower:
            return get_body(f)[:400]
    return "(body not found)"


def load_pn_paths() -> dict[str, Path]:
    """Title→path map for all PNs."""
    result = {}
    for f in PN_DIR.rglob("*.md"):
        result[f.stem] = f
    return result


# ---------------------------------------------------------------------------
# Commands
# ---------------------------------------------------------------------------
def cmd_status(_args):
    total = 0
    with_conn = 0
    need_conn = 0
    total_untyped_links = 0

    for f in PN_DIR.rglob("*.md"):
        txt = f.read_text(encoding="utf-8", errors="ignore")
        if not re.search(r'type:\s*["\']?permanent', txt):
            continue
        total += 1
        if SECTION_HEADER in txt:
            with_conn += 1
        else:
            untyped = extract_untyped_pn_links(f)
            if untyped:
                need_conn += 1
                total_untyped_links += len(untyped)

    print(json.dumps({
        "ok": True,
        "total_pns": total,
        "already_have_typed_connections": with_conn,
        "need_typed_connections": need_conn,
        "total_untyped_links": total_untyped_links,
        "pct_covered": round(100 * with_conn / total, 1) if total else 0,
    }, indent=2))


def cmd_scan(args):
    limit = args.limit or 50
    pn_paths = load_pn_paths()
    batches = []

    for f in sorted(PN_DIR.rglob("*.md")):
        if len(batches) >= limit:
            break
        txt = f.read_text(encoding="utf-8", errors="ignore")
        if not re.search(r'type:\s*["\']?permanent', txt):
            continue
        # Skip if already has Typed Connections (unless --all)
        if SECTION_HEADER in txt and not getattr(args, 'all', False):
            continue

        untyped = extract_untyped_pn_links(f)
        if not untyped:
            continue

        # Source body excerpt
        body = get_body(f)
        body_clean = body.split(SECTION_HEADER)[0].strip()
        # Title
        title_m = re.search(r'^# (.+)', body_clean, re.MULTILINE)
        title = title_m.group(1).strip() if title_m else f.stem

        targets = []
        for link in untyped[:6]:  # max 6 targets per PN
            target_body = get_body_excerpt(link["title"])
            targets.append({
                "title": link["title"],
                "context_in_source": link["context_after"][:80],
                "target_body_excerpt": target_body[:250],
            })

        if targets:
            batches.append({
                "note_path": str(f.relative_to(VAULT_INNER)),
                "source_title": title,
                "source_body_excerpt": body_clean[:350],
                "targets": targets,
            })

    result = {
        "ok": True,
        "total_batches": len(batches),
        "total_pairs": sum(len(b["targets"]) for b in batches),
        "batches": batches,
    }

    if getattr(args, 'json', False):
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        print(f"Batches: {len(batches)} PNs · {result['total_pairs']} pairs")
        print()
        for b in batches[:8]:
            print(f"  {b['source_title'][:60]}")
            for t in b["targets"]:
                print(f"    → {t['title'][:55]}")
        if len(batches) > 8:
            print(f"  ... and {len(batches)-8} more")


def cmd_preview(args):
    query = " ".join(args.title).strip()
    query_lower = query.lower()

    target_file = None
    for f in PN_DIR.rglob("*.md"):
        if query_lower in f.stem.lower():
            target_file = f
            break

    if not target_file:
        print(json.dumps({"ok": False, "error": f"PN not found: {query}"}))
        return

    untyped = extract_untyped_pn_links(target_file)
    body = get_body(target_file)
    title_m = re.search(r'^# (.+)', body, re.MULTILINE)
    title = title_m.group(1).strip() if title_m else target_file.stem

    targets = []
    for link in untyped:
        targets.append({
            "title": link["title"],
            "context_in_source": link["context_after"][:80],
            "target_body_excerpt": get_body_excerpt(link["title"])[:250],
        })

    print(json.dumps({
        "ok": True,
        "note_path": str(target_file.relative_to(VAULT_INNER)),
        "source_title": title,
        "source_body_excerpt": body.split(SECTION_HEADER)[0].strip()[:350],
        "has_typed_connections": SECTION_HEADER in (get_body(target_file)),
        "untyped_pn_links": len(untyped),
        "targets": targets,
    }, indent=2, ensure_ascii=False))


def cmd_apply(args):
    try:
        payload = json.loads(args.json_payload)
    except Exception as e:
        print(json.dumps({"ok": False, "error": f"Invalid JSON: {e}"}))
        return

    if isinstance(payload, dict):
        payload = [payload]

    applied = []
    errors = []

    for item in payload:
        note_path = item.get("note_path", "")
        connections = item.get("connections", [])
        if not note_path or not connections:
            continue

        valid = [
            c for c in connections
            if c.get("type", "").lower() not in SKIP_TYPES
            and c.get("type", "").lower() in VALID_TYPES
            and c.get("sentence", "").strip()
        ]
        if not valid:
            continue

        fpath = VAULT_INNER / note_path
        if not fpath.exists():
            errors.append(f"Not found: {note_path}")
            continue

        try:
            content = fpath.read_text(encoding="utf-8")

            conn_lines = []
            for c in valid:
                sentence = c["sentence"].strip()
                if not sentence.endswith("."):
                    sentence += "."
                conn_lines.append(f"- {sentence}")

            new_section = (
                f"\n\n{SECTION_HEADER}\n\n"
                + "\n".join(conn_lines)
                + "\n"
            )

            if SECTION_HEADER in content:
                # Replace existing section
                content = re.sub(
                    rf'({re.escape(SECTION_HEADER)}\n)[\s\S]*',
                    SECTION_HEADER + "\n\n" + "\n".join(conn_lines) + "\n",
                    content,
                )
            else:
                content = content.rstrip() + new_section

            if "enriched:" not in content:
                content = re.sub(
                    r"(created:.*?\n)",
                    r"\1enriched: " + TODAY + "\n",
                    content,
                    count=1,
                )

            fpath.write_text(content, encoding="utf-8")
            applied.append({
                "note": note_path,
                "connections_written": len(valid),
                "types": [c["type"] for c in valid],
            })

        except Exception as e:
            errors.append(f"{note_path}: {e}")

    print(json.dumps({
        "ok": True,
        "applied": len(applied),
        "errors": len(errors),
        "detail": applied,
        **({"error_list": errors[:5]} if errors else {}),
    }, indent=2, ensure_ascii=False))


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------
def main():
    p = argparse.ArgumentParser(description="Typed Connections enricher")
    sub = p.add_subparsers(dest="command")

    sub.add_parser("status", help="Typed Connections coverage status")

    p_scan = sub.add_parser("scan", help="Export untyped PN→PN pairs for classification")
    p_scan.add_argument("--limit", type=int, default=50, help="Max PNs (default 50)")
    p_scan.add_argument("--all", action="store_true", help="Include PNs that already have connections")
    p_scan.add_argument("--json", action="store_true", help="Full JSON output")

    p_apply = sub.add_parser("apply", help="Write classified connections into the vault")
    p_apply.add_argument("--json", dest="json_payload", required=True)

    p_prev = sub.add_parser("preview", help="Preview the pairs of one specific PN")
    p_prev.add_argument("title", nargs="+")

    args = p.parse_args()
    {
        "status":  cmd_status,
        "scan":    cmd_scan,
        "apply":   cmd_apply,
        "preview": cmd_preview,
    }.get(args.command, lambda _: p.print_help())(args)


if __name__ == "__main__":
    main()
